#!/usr/bin/env python3
"""챕터 스펙(JSON)을 파이썬으로 읽기 좋게 쓰고 찍어내는 스크립트.

퀴즈의 기출 출처(src)는 손으로 적지 않는다. topic_rounds.json(시대분류 74회차에서
뽑은 '개념 → 출제 회차' 색인)에서 R()로 조회해 채운다. 손으로 적으면 반드시
틀리고, 틀려도 티가 안 나기 때문이다.

  python3 author_specs.py          # specs/*.json 생성
  python3 make_chapter.py --all    # 그 스펙으로 챕터 HTML 생성
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SPECS = os.path.join(HERE, 'specs')
os.makedirs(SPECS, exist_ok=True)
IDX = json.load(open(os.path.join(HERE, 'topic_rounds.json'), encoding='utf-8'))

_missing = []


def R(*keys, cap=12):
    """개념 이름들로 출제 회차를 모아 정렬해 돌려준다."""
    out = set()
    for k in keys:
        if k in IDX:
            out |= set(IDX[k])
        else:
            _missing.append(k)
    return sorted(out)[:cap]


def Q(q, right, wrong, fb_wrong, fb_right, *src_keys):
    return {'q': q, 'opts': [right, wrong], 'src': R(*src_keys),
            'fb': [fb_wrong, fb_right]}


def npc(key, name, portrait, icon, beats, quiz=None, ends=False, note=None):
    d = {'name': name, 'portrait': portrait, 'icon': icon,
         'beats': [{'t': b} if isinstance(b, str) else b for b in beats]}
    if quiz:
        d['quiz'] = quiz
    if ends:
        d['endsChapter'] = True
    if note:
        d['note'] = note
    return key, d


def write(spec):
    p = os.path.join(SPECS, spec['id'] + '.json')
    json.dump(spec, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    nq = sum(len(d.get('quiz', [])) for d in spec['npcData'].values())
    bad = [k for k, d in spec['npcData'].items()
           for q in d.get('quiz', []) if not q['src']]
    print(f"{spec['id']:12s} 퀴즈 {nq:2d}" + (f"  ⚠ 출처없음 {len(bad)}" if bad else ''))
    return nq


