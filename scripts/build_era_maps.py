def js_areas(items):
    out = []
    for n, col, pts, (tlo, tla) in items:
        tx, ty = xy(tlo, tla)
        out.append("{ pts:'%s', n:'%s', tx:%.0f, ty:%.0f, c:'%s' }"
                   % (pts, n, tx, ty, C[col]))
    return 'areas:[ ' + ', '.join(out) + ' ],'


