def xy(lon, lat):
    return ((lon - 124.0) / 7.0 * 100.0, (43.3 - lat) / 9.5 * 150.0)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    poly = '--poly' in sys.argv

    names = args or sorted(PLACES)
    pts = []
    for n in names:
        if n not in PLACES:
            print('!! 표에 없는 지명:', n); continue
        lon, lat, memo = PLACES[n]
        x, y = xy(lon, lat)
        pts.append((x, y))
        if not poly:
            print('%-14s x=%6.1f  y=%6.1f   (%.2f, %.2f) %s'
                  % (n, x, y, lon, lat, memo))
    if poly:
        print("pts:'" + ' '.join('%.0f,%.0f' % p for p in pts) + "'")
        print('(꼭짓점 %d개 — 다각형은 시계/반시계 어느 쪽이든 된다)' % len(pts))


if __name__ == '__main__':
    main()
